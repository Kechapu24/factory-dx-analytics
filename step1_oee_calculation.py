# =========================================================
# ステップ1: 設備データを読み込んで OEE(設備総合効率) を計算する
# =========================================================
#
# このプログラムがやることは、たった3つだけです。
#   1. CSVファイル(表形式のデータ)を読み込む
#   2. 稼働率・良品率・OEEを計算する
#   3. 結果を画面に表示する
#
# 難しい単語が出てきますが、慌てず1行ずつ確認していきましょう。

import pandas as pd
# pandas(パンダス)は「表形式のデータ(Excelのようなもの)」を
# Pythonで簡単に扱うための道具箱です。「pd」という短い名前で呼べるようにしています。


# ---------------------------------------------------------
# 1. CSVファイルを読み込む
# ---------------------------------------------------------
df = pd.read_csv("equipment_data.csv")
# equipment_data.csv というファイルを読み込んで、
# 「df」という名前の表(データフレームと呼びます)に入れています。
# df は DataFrame(データフレーム)の略で、pandasではお決まりの名前です。

print("===== 読み込んだデータ =====")
print(df)
print()
# ここで一度、読み込んだデータを表示して中身を確認します。
# 「本当に思った通りのデータが読み込めているか」を毎回確認する癖をつけると、
# 後々のバグ(間違い)を早期に発見できます。


# ---------------------------------------------------------
# 2. 稼働率・良品率・OEEを計算する
# ---------------------------------------------------------

# 稼働率 = 稼働時間 ÷ (稼働時間 + 停止時間)
df["稼働率"] = df["稼働時間分"] / (df["稼働時間分"] + df["停止時間分"])

# 良品率 = (生産数 - 不良数) ÷ 生産数
df["良品率"] = (df["生産数"] - df["不良数"]) / df["生産数"]

# OEE(簡易版) = 稼働率 × 良品率
# ※本来は「性能稼働率」も含めた3要素の掛け算ですが、
#   最初は理解しやすいようにシンプルな2要素版から始めます。
df["OEE"] = df["稼働率"] * df["良品率"]

# df["新しい列名"] = 計算式 と書くだけで、
# 表(df)に新しい列(縦の項目)を追加できます。
# これがpandasの一番便利なところです。

print("===== 計算結果 =====")
# 見やすいように、パーセント表示に丸めて表示します
result = df.copy()
result["稼働率"] = (result["稼働率"] * 100).round(1).astype(str) + "%"
result["良品率"] = (result["良品率"] * 100).round(1).astype(str) + "%"
result["OEE"] = (result["OEE"] * 100).round(1).astype(str) + "%"
print(result[["設備ID", "日付", "稼働率", "良品率", "OEE"]])
print()


# ---------------------------------------------------------
# 3. 設備ごとの平均OEEを出してみる(ここが分析の第一歩)
# ---------------------------------------------------------
print("===== 設備ごとの平均OEE(3日間平均) =====")
avg_by_equipment = df.groupby("設備ID")["OEE"].mean()
# groupby(グループバイ)は「設備IDが同じ行同士をひとまとめにして計算する」機能です。
# 例えば「EQ-001の3日分のOEEの平均を出す」といったことが1行でできます。

avg_by_equipment = (avg_by_equipment * 100).round(1)
print(avg_by_equipment.astype(str) + "%")
print()

