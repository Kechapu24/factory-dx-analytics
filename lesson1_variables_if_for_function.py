# ---------------------------------------------------------
# パート2: if文(条件分岐)
# ---------------------------------------------------------
# 「もし〜なら、こうする」を表現する構文です。

oee = 0.75

if oee >= 0.85:
    print("状態: 優良")
elif oee >= 0.6:
    print("状態: 注意")
else:
    print("状態: 危険")

# 上から順番に条件をチェックし、最初に当てはまったブロックだけが実行されます。
# oee=0.75 は「0.85以上」ではないが「0.6以上」なので、「状態: 注意」が表示されます。

