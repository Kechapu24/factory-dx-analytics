# ---------------------------------------------------------
# パート3: for文(繰り返し)
# ---------------------------------------------------------
# 同じ処理を、リストの中身に対して繰り返し実行します。

equipment_list = ["EQ-001", "EQ-002", "EQ-003"]

for eq in equipment_list:
    print(f"{eq} のデータをチェック中...")

# equipment_list の中身を1個ずつ取り出して、"eq"という変数に入れながら、
# ブロックの中身(print文)を繰り返し実行しています。

# ■ 練習問題3
# oee_list = [0.92, 0.65, 0.45] というリストを作ってください。
# for文で1個ずつ取り出し、パート2のif文と組み合わせて、
# それぞれの値が「優良/注意/危険」のどれに当たるか表示してみてください。
# (ヒント: for文の中にif文を書きます)

oee_list = [0.92, 0.65, 0.45]

for oee in oee_list:
    if oee >= 0.85:
        print(oee,"優良")
    elif oee >= 0.6:
        print(oee,"注意")
    else :
        print(oee,"危険")

# ---------------------------------------------------------
# パート4: 関数
# ---------------------------------------------------------
# 「よく使う処理」に名前をつけて、何度でも呼び出せるようにする仕組みです。

def calc_oee_status(oee_value):
    """OEEの値を受け取って、状態の文字列を返す関数"""
    if oee_value >= 0.85:
        return "優良"
    elif oee_value >= 0.6:
        return "注意"
    else:
        return "危険"

# 使ってみる
result1 = calc_oee_status(0.92)
result2 = calc_oee_status(0.5)
print("0.92の判定:", result1)
print("0.5の判定:", result2)

# 練習問題2・3で書いたif文を、この関数の中に「まとめた」だけです。
# 一度関数にしておけば、何度も同じコードを書かずに済みます。

# ■ 練習問題4
# calc_oee_status(0.7) の結果を、print()で表示してみてください。

result3 = calc_oee_status(0.7)
print(result3)

