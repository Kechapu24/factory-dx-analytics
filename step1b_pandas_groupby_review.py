# 復習: pandasの基本 と groupby の仕組み
# =========================================================
# 「表を分解して、また組み立て直す」感覚を、途中経過を全部表示しながら確認します。

import pandas as pd

df = pd.read_csv("equipment_data.csv")

print("##################################################")
print("# パート1: DataFrame と Series の違いを見る")
print("##################################################")

print("\n--- df 全体(DataFrame。表そのもの) ---")
print(df)
print(f"\ndfの型: {type(df)}")

print("\n--- df['設備ID'] だけ取り出す(Series。1列だけ) ---")
print(df["設備ID"])
print(f"\ndf['設備ID']の型: {type(df['設備ID'])}")
# DataFrame(表全体)からSeries(1列)を取り出しただけ、というのがポイントです。


print("\n\n##################################################")
print("# パート2: groupby はエクセルのピボットテーブルと同じ")
print("##################################################")

print("\n--- ステップ1: groupbyした直後(まだ計算はしていない) ---")
grouped = df.groupby("設備ID")
print(grouped)
print("↑ この時点では『設備IDごとにグループ分けの準備をしただけ』の状態です。")
print("  中身はまだ計算されていません。箱に仕分けしただけ、というイメージです。")

print("\n--- ステップ2: 各グループの中身を実際に覗いてみる ---")
for name, group in grouped:
    print(f"\n設備ID = {name} のグループの中身:")
    print(group)
# for文でgroupbyの中身を1グループずつ取り出して表示しています。
# 「EQ-001の3行」「EQ-002の3行」「EQ-003の3行」に分かれているのが分かるはずです。

print("\n--- ステップ3: グループごとに平均を計算する ---")
avg_result = df.groupby("設備ID")["不良数"].mean()
print(avg_result)
print("↑ グループ分けした『不良数』の列だけを取り出して、平均を計算しました。")

print("\n--- ステップ4: 複数の列をまとめて集計することもできる ---")
avg_result_multi = df.groupby("設備ID")[["稼働時間分", "停止時間分", "不良数"]].mean()
print(avg_result_multi)
print("↑ 前回の分析で使った『停止時間の平均』はこうやって出していました。")

print("\n★ groupbyは「グループ分け → 列を選ぶ → 計算方法(mean, sum等)を指定」")
print("  の3ステップだと覚えると、迷わなくなります。")
